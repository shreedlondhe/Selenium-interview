//    What is java collection?
//    Ans:    Java collections is combination of interfaces (like List, Set, and Map)  and classes (ArrayList, HashSet, HashMap).
//           All of these are part of the java.util package
//           Iterable is parent interface
//           Why Do We Need Collections?
//                    Problem with Arrays:
//                                       Fixed size
//                                       Store only primitive data
//                                       Store only homogeneous data
//                    Solution: Java Collections
//                                       Dynamic size (grow/shrink)
//                                       Store homogeneous Data
//                                       Better performance
//                                       Store object Wrapper classes
//                                       Easy data handling



// // Collections methods
// | Sr. No. | Method           | Example                                                                           | Output                          |
// | ------: | ---------------- | --------------------------------------------------------------------------------- | ------------------------------- |
// |       1 | `addAll()`       | `Collections.addAll(list, 10, 20, 30);`                                           | `[10, 20, 30]`                  |
// |       2 | `max()`          | `Collections.max(Arrays.asList(10, 30, 20));`                                     | `30`                            |
// |       3 | `min()`          | `Collections.min(Arrays.asList(10, 30, 20));`                                     | `10`                            |
// |       4 | `sort()`         | `Collections.sort(list);` where `list = [30, 10, 20]`                             | `[10, 20, 30]`                  |
// |       5 | `reverse()`      | `Collections.reverse(list);` where `list = [10, 20, 30]`                          | `[30, 20, 10]`                  |
// |       6 | `reverseOrder()` | `Collections.sort(list, Collections.reverseOrder());` where `list = [10, 30, 20]` | `[30, 20, 10]`                  |
// |       7 | `frequency()`    | `Collections.frequency(Arrays.asList(10, 20, 10, 30), 10);`                       | `2`                             |
// |       8 | `swap()`         | `Collections.swap(list, 0, 2);` where `list = [10, 20, 30]`                       | `[30, 20, 10]`     
// |       9 |  sort+reverse    |  Collections.sort(list,Collections,reverseOrder())
// ----------------------------------------------------------------------------------------------------------------------------------------------------

